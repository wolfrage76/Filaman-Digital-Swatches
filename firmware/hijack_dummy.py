Import("env")

import os
import glob


def ensure_arduino_component():
    # The .dummy REQUIRES the `arduino` IDF component, but pioarduino's Arduino
    # source package is named framework-arduinoespressif32-src-<hash>, so IDF can't
    # resolve it as "arduino". Expose it under that name via a project components/
    # dir (auto-scanned by IDF).
    pkgs = env.subst("$PROJECT_PACKAGES_DIR")
    matches = sorted(glob.glob(os.path.join(pkgs, "framework-arduinoespressif32-src-*")))
    if not matches:
        print("[hijack_dummy] arduino-src package not found; skipping component link")
        return
    comp_dir = os.path.join(env.subst("$PROJECT_DIR"), "components")
    link = os.path.join(comp_dir, "arduino")
    os.makedirs(comp_dir, exist_ok=True)
    if os.path.islink(link) or os.path.exists(link):
        try:
            if os.path.realpath(link) == os.path.realpath(matches[0]):
                return
            os.remove(link)
        except OSError:
            return
    os.symlink(matches[0], link)
    print("[hijack_dummy] linked components/arduino -> {}".format(os.path.basename(matches[0])))

# pioarduino's custom_sdkconfig builds a ".dummy" component that defaults to a
# hello-world lib-builder stub (sketch.cpp), NOT our app — so our firmware never
# links. This pre-script rewrites .dummy to compile OUR sources instead, with the
# include dirs for our libraries, so the from-source IDF build (with XIP_FROM_PSRAM)
# produces the real firmware. Runs every build so a clean can't revert it.
# See memory: idf-xip-build-setup.

PROJECT_DIR = env.subst("$PROJECT_DIR")
LIBDEPS = os.path.join(env.subst("$PROJECT_LIBDEPS_DIR"), env.subst("$PIOENV"))
DUMMY = os.path.join(PROJECT_DIR, ".dummy")
SRC = os.path.join(PROJECT_DIR, "src")


def quote(p):
    return '"{}"'.format(p)


def app_sources():
    out = []
    for root, _dirs, files in os.walk(SRC):
        for f in files:
            if f.endswith(".cpp"):
                out.append(os.path.join(root, f))
    # HTTPUpdateServer is not compiled into the Arduino IDF component; WebServer is.
    pkgs = env.subst("$PROJECT_PACKAGES_DIR")
    matches = sorted(glob.glob(os.path.join(pkgs, "framework-arduinoespressif32-src-*")))
    if matches:
        lib_src = os.path.join(matches[0], "libraries", "HTTPUpdateServer", "src")
        if os.path.isdir(lib_src):
            for root, _dirs, files in os.walk(lib_src):
                for f in files:
                    if f.endswith(".cpp"):
                        out.append(os.path.join(root, f))
    return sorted(out)


def include_dirs():
    dirs = [
        ".",
        SRC,
        os.path.join(PROJECT_DIR, "include"),
        os.path.join(LIBDEPS, "lvgl"),
        os.path.join(LIBDEPS, "lvgl", "src"),
        os.path.join(LIBDEPS, "GFX Library for Arduino", "src"),
        os.path.join(LIBDEPS, "PubSubClient", "src"),
        os.path.join(LIBDEPS, "ArduinoJson", "src"),
        os.path.join(LIBDEPS, "TAMC_GT911"),
    ]
    # Arduino-as-component builds do not auto-add every bundled library the way
    # PlatformIO LDF does. Web portal needs WebServer + HTTPUpdateServer.
    pkgs = env.subst("$PROJECT_PACKAGES_DIR")
    matches = sorted(glob.glob(os.path.join(pkgs, "framework-arduinoespressif32-src-*")))
    if matches:
        lib_root = os.path.join(matches[0], "libraries")
        for name in ("WebServer", "HTTPUpdateServer", "HTTPUpdate", "Update", "WiFi", "Network"):
            src = os.path.join(lib_root, name, "src")
            if os.path.isdir(src):
                dirs.append(src)
    return dirs


def write_hijack():
    srcs = app_sources()
    if not srcs:
        print("[hijack_dummy] no src/*.cpp found; skipping")
        return
    lines = [
        "# Auto-generated by hijack_dummy.py — do not edit by hand.",
        "# Makes pioarduino's custom_sdkconfig build OUR app, not its hello-world stub.",
        "idf_component_register(",
        "  SRCS",
    ]
    lines += ["    {}".format(quote(s)) for s in srcs]
    lines.append("  INCLUDE_DIRS")
    lines += ["    {}".format(quote(d)) for d in include_dirs()]
    lines.append(
        "  REQUIRES arduino esp_wifi esp_lcd driver esp_psram nvs_flash esp_timer esp_hw_support"
    )
    lines.append(")")
    os.makedirs(DUMMY, exist_ok=True)
    with open(os.path.join(DUMMY, "CMakeLists.txt"), "w") as f:
        f.write("\n".join(lines) + "\n")
    # Empty the stub so its setup()/loop() don't clash with src/main.cpp.
    with open(os.path.join(DUMMY, "sketch.cpp"), "w") as f:
        f.write("// Emptied by hijack_dummy.py; real setup()/loop() are in src/main.cpp\n")
    print("[hijack_dummy] .dummy -> app ({} sources)".format(len(srcs)))


ensure_arduino_component()
write_hijack()
